// Copyright check: how safe each clip and song is to post, judged from where it came from, its license and
// (for YouTube links) what YouTube says about it: a Creative Commons license, or a released song it contains.
// It can't hear or see the footage itself, so it's a guide, not a guarantee.

// levels, safest first: label on the badge, the color class, and what it means
export const LEVELS = {
  free: { rank: 0, short: 'Free', label: 'Free to use' },
  credit: { rank: 1, short: 'Credit', label: 'Free with credit' },
  unknown: { rank: 2, short: 'Your file', label: 'Your own file' },
  limited: { rank: 3, short: 'Limited', label: 'Restricted license' },
  owned: { rank: 4, short: 'Owned', label: 'Owned by someone else' },
  claimed: { rank: 5, short: 'Claim risk', label: 'Likely to be claimed' },
};

const STREAMS = new Set(['twitch', 'kick', 'twitchgame', 'kickgame', 'kicktrend', 'twitchtop', 'streamtrend']);
const FREE_STOCK = { pexels: 'Pexels', pixabay: 'Pixabay', mixkit: 'Mixkit', destockd: 'Destockd (public domain)' };

// where a pasted link points
export function sourceFromUrl(url) {
  let h = '';
  try { h = new URL(url).hostname.replace(/^(www|m|music|clips)\./, ''); } catch { return ''; }
  if (/(^|\.)youtube\.com$|^youtu\.be$/.test(h)) return 'youtube';
  if (/twitch\.tv$/.test(h)) return 'twitch';
  if (/kick\.com$/.test(h)) return 'kick';
  if (/dailymotion\.com$|^dai\.ly$/.test(h)) return 'dailymotion';
  if (/medal\.tv$/.test(h)) return 'medal';
  if (/giphy\.com$/.test(h)) return 'giphy';
  if (/tiktok\.com$/.test(h)) return 'tiktok';
  if (/instagram\.com$/.test(h)) return 'instagram';
  if (/(^|\.)x\.com$|twitter\.com$/.test(h)) return 'x';
  if (/pexels\.com$/.test(h)) return 'pexels';
  if (/pixabay\.com$/.test(h)) return 'pixabay';
  if (/mixkit\.co$/.test(h)) return 'mixkit';
  if (/thepartwhere\.com$/.test(h)) return 'moments';
  if (/yarn\.co$/.test(h)) return 'yarn';
  if (/freesound\.org$/.test(h)) return 'freesound';
  if (/freemusicarchive\.org$/.test(h)) return 'fma';
  if (/ccmixter\.org$/.test(h)) return 'ccmixter';
  if (/archive\.org$/.test(h)) return 'iaaudio';
  return 'web';
}

// a license written any way ("CC BY 4.0", "cc-by-nc", "Public domain", "Attribution-NonCommercial") -> level
export function licenseLevel(text) {
  const t = String(text || '').toLowerCase();
  if (!t.trim()) return null;
  if (/\bcc0\b|public domain|\bpdm\b|no rights reserved|free license/.test(t)) return 'free';
  if (/\bnc\b|by-nc|noncommercial|non-commercial|\bnd\b|by-nd|noderiv|no deriv/.test(t)) return 'limited';
  if (/cc[\s-]?by|attribution|creative commons|\bcc\b|sampling\+/.test(t)) return 'credit';
  return null;
}
// the license part of a card line like "artist · CC BY 4.0"
const licenseIn = (s) => String(s || '').split(' · ').slice(1).join(' · ');
const nameIn = (s) => String(s || '').split(' · ')[0].trim();

// info: { kind: 'clip' | 'song', source, url, title, channel, license, moment, local, tags: { artist, title }, meta: (from /api/rights) }
export function rightsOf(info = {}) {
  const kind = info.kind === 'song' ? 'song' : 'clip';
  const src = info.source || (info.url ? sourceFromUrl(info.url) : '') || (info.local ? 'local' : '');
  const meta = info.meta || {};
  const who = (info.channel && nameIn(info.channel)) || meta.uploader || '';
  const title = info.title || meta.track || '';
  const lic = info.license || licenseIn(info.channel) || '';
  const out = (level, why, credit = '') => ({ level, ...LEVELS[level], why, credit, source: src });
  const creditLine = (by, l, site) => `“${title || (kind === 'song' ? 'Song' : 'Clip')}”${by ? ` by ${by}` : ''}${l ? ` (${l})` : ''}${site ? `, via ${site}` : ''}`;

  // things YouTube itself reports (any yt-dlp link): a released song inside, or a Creative Commons license
  const song = meta.track && (meta.artist || meta.label) ? `“${meta.track}” by ${meta.artist || meta.label}` : '';
  if (meta.label || meta.autoGenerated || song) {
    return out('claimed', `${song ? `Contains ${song}` : 'A released song'}${meta.label ? ` (${meta.label})` : ''}. Music like this is usually muted or claimed on TikTok, Instagram and YouTube. Use the platform's own sound instead, or a free song.`);
  }
  if (/creative commons/i.test(meta.license || '')) {
    return out('credit', `The uploader shared it under a Creative Commons license: credit them when you post.`, creditLine(who, 'CC BY', 'YouTube'));
  }

  if (info.moment || src === 'moments' || src === 'yarn') {
    return out('claimed', 'A scene from a movie or TV show. Studios often claim or block these, especially longer clips.');
  }
  if (FREE_STOCK[src]) return out('free', `Free stock from ${FREE_STOCK[src]}: free to use, no credit needed.`);
  if (src === 'commons' || src === 'openverse' || src === 'fma' || src === 'ccmixter' || src === 'freesound' || src === 'iaaudio') {
    const site = { commons: 'Wikimedia Commons', openverse: 'Openverse', fma: 'Free Music Archive', ccmixter: 'ccMixter', freesound: 'Freesound', iaaudio: 'Internet Archive' }[src];
    const lv = licenseLevel(lic);
    const shown = lic.replace(/\s*—\s*credit .*$/i, '').trim();
    if (lv === 'free') return out('free', `${shown || 'Public domain'} on ${site}: free to use.`);
    if (lv === 'credit') return out('credit', `${shown} on ${site}: free to use if you credit the creator.`, creditLine(who, shown, site));
    if (lv === 'limited') return out('limited', `${shown} on ${site}: credit the creator, and it can't be used commercially (no sponsored or monetized posts)${/nd|deriv/i.test(shown) ? ' or changed' : ''}.`, creditLine(who, shown, site));
    return out('limited', `Check the license on ${site} before posting: it isn't shown here.`, creditLine(who, '', site));
  }
  if (src === 'archival') return out('limited', 'Vintage footage from A/V Geeks: check the license terms on their site before posting.');
  if (STREAMS.has(src)) {
    return out('owned', `From ${who ? `${who}'s` : 'a'} stream. Clipping streams is common, but the clip belongs to the streamer: credit them${who ? ` (@${who})` : ''}. Music playing on stream can get your post muted.`, who ? `Clip from @${who} on ${src.startsWith('kick') ? 'Kick' : 'Twitch'}` : '');
  }
  if (kind === 'song' && (src === 'youtube' || src === 'ytsong')) {
    return out('claimed', 'A song from YouTube. Popular songs are usually muted or claimed when you post: use the platform\'s own sound library, or a free song from Find songs.');
  }
  if (['youtube', 'ytchannel', 'shorts', 'dailymotion', 'medal', 'tiktok', 'instagram', 'x', 'giphy', 'web'].includes(src)) {
    return out('owned', `${who ? `Belongs to ${who}` : 'Belongs to whoever posted it'}. Reposting someone else's video can get claimed or taken down: credit them, add your own commentary, or ask first.`, who ? `Clip from ${who}` : '');
  }
  // your own files
  const tags = info.tags || {};
  if (kind === 'song' && tags.artist && tags.title) {
    return out('claimed', `Looks like a released song (“${tags.title}” by ${tags.artist}). Music like this is usually muted or claimed when you post.`);
  }
  return out('unknown', kind === 'song' ? 'Your own file: Cutsona can\'t tell who owns this song. Fine if you made it or have the rights.' : 'Your own file: Cutsona can\'t tell who owns it. Fine if you filmed it or have the rights.');
}

// the overall verdict for an edit: the riskiest item wins
export function summarize(list) {
  const items = list.filter(Boolean);
  const worst = items.reduce((w, r) => (!w || r.rank > w.rank ? r : w), null);
  const count = (lv) => items.filter((r) => r.level === lv).length;
  const credits = [...new Set(items.map((r) => r.credit).filter(Boolean))];
  return { worst, count, credits, risky: count('claimed') + count('owned') };
}

// ID3 tags of an MP3 you dropped in (artist, title, copyright): enough to spot a released song
export function readId3(buf) {
  try {
    const b = new Uint8Array(buf);
    if (b.length < 10 || b[0] !== 0x49 || b[1] !== 0x44 || b[2] !== 0x33) return {};
    const ver = b[3], size = ((b[6] & 127) << 21) | ((b[7] & 127) << 14) | ((b[8] & 127) << 7) | (b[9] & 127);
    const end = Math.min(b.length, 10 + size), out = {};
    const want = { TPE1: 'artist', TIT2: 'title', TCOP: 'copyright', TPUB: 'label', TP1: 'artist', TT2: 'title' };
    let i = 10;
    while (i + (ver === 2 ? 6 : 10) <= end) {
      const id = String.fromCharCode(...b.slice(i, i + (ver === 2 ? 3 : 4)));
      if (!/^[A-Z0-9]{3,4}$/.test(id)) break;
      const len = ver === 2 ? (b[i + 3] << 16) | (b[i + 4] << 8) | b[i + 5]
        : ver === 4 ? ((b[i + 4] & 127) << 21) | ((b[i + 5] & 127) << 14) | ((b[i + 6] & 127) << 7) | (b[i + 7] & 127)
        : (b[i + 4] << 24) | (b[i + 5] << 16) | (b[i + 6] << 8) | b[i + 7];
      const start = i + (ver === 2 ? 6 : 10);
      if (len <= 0 || start + len > end) break;
      if (want[id]) {
        const enc = b[start], data = b.slice(start + 1, start + len);
        const text = enc === 1 || enc === 2 ? new TextDecoder(enc === 1 ? 'utf-16' : 'utf-16be').decode(data) : new TextDecoder(enc === 3 ? 'utf-8' : 'latin1').decode(data);
        out[want[id]] = text.replace(/\0+$/, '').replace(/\0/g, ' / ').trim();
      }
      i = start + len;
    }
    return out;
  } catch { return {}; }
}
