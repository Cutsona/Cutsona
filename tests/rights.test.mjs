import test from 'node:test';
import assert from 'node:assert/strict';
import { rightsOf, licenseLevel, sourceFromUrl, summarize, readId3 } from '../app/js/rights.js';

test('free stock is free, movie scenes are claim risks', () => {
  assert.equal(rightsOf({ source: 'pexels' }).level, 'free');
  assert.equal(rightsOf({ source: 'mixkit' }).level, 'free');
  assert.equal(rightsOf({ source: 'youtube', moment: true, title: 'Joker stairs' }).level, 'claimed');
  assert.equal(rightsOf({ source: 'yarn' }).level, 'claimed');
});

test('licenses are read however they are written', () => {
  assert.equal(licenseLevel('CC0 1.0'), 'free');
  assert.equal(licenseLevel('Public domain'), 'free');
  assert.equal(licenseLevel('CC BY 4.0'), 'credit');
  assert.equal(licenseLevel('cc-by-sa'), 'credit');
  assert.equal(licenseLevel('Attribution-NonCommercial 3.0'), 'limited');
  assert.equal(licenseLevel('CC BY-ND'), 'limited');
  assert.equal(licenseLevel(''), null);
});

test('open licenses come with a credit line', () => {
  const r = rightsOf({ source: 'commons', title: 'Sunset', license: 'CC BY-SA 4.0 — credit Jane Doe', channel: 'Jane Doe' });
  assert.equal(r.level, 'credit');
  assert.match(r.credit, /Sunset.*Jane Doe.*CC BY-SA 4\.0.*Wikimedia Commons/);
  const fs = rightsOf({ kind: 'song', source: 'freesound', title: 'Whoosh', channel: 'bob · CC BY-NC 4.0' });
  assert.equal(fs.level, 'limited');
});

test('stream clips belong to the streamer, YouTube songs get claimed', () => {
  const t = rightsOf({ source: 'twitch', channel: 'xqc' });
  assert.equal(t.level, 'owned');
  assert.match(t.why, /@xqc/);
  assert.equal(rightsOf({ kind: 'song', source: 'youtube', title: 'Some hit' }).level, 'claimed');
  assert.equal(rightsOf({ kind: 'song', source: 'fma', channel: 'Artist · Creative Commons' }).level, 'credit');
});

test('what YouTube reports wins: a song inside, or Creative Commons', () => {
  assert.equal(rightsOf({ source: 'youtube', meta: { track: 'Blinding Lights', artist: 'The Weeknd' } }).level, 'claimed');
  assert.equal(rightsOf({ source: 'youtube', meta: { autoGenerated: true } }).level, 'claimed');
  assert.equal(rightsOf({ source: 'youtube', meta: { license: 'Creative Commons Attribution license (reuse allowed)', uploader: 'NASA' } }).level, 'credit');
});

test('pasted links and your own files', () => {
  assert.equal(sourceFromUrl('https://clips.twitch.tv/AbcDef'), 'twitch');
  assert.equal(sourceFromUrl('https://kick.com/x/clips/y'), 'kick');
  assert.equal(sourceFromUrl('https://youtu.be/abc'), 'youtube');
  assert.equal(rightsOf({ url: 'https://www.youtube.com/watch?v=x' }).level, 'owned');
  assert.equal(rightsOf({ local: true }).level, 'unknown');
  assert.equal(rightsOf({ kind: 'song', local: true, tags: { artist: 'Drake', title: 'Hotline Bling' } }).level, 'claimed');
});

test('summary: the riskiest item wins, credits are collected once', () => {
  const s = summarize([rightsOf({ source: 'pexels' }), rightsOf({ source: 'twitch', channel: 'a' }), rightsOf({ source: 'twitch', channel: 'a' })]);
  assert.equal(s.worst.level, 'owned');
  assert.equal(s.risky, 2);
  assert.equal(s.credits.length, 1);
});

test('ID3 tags of a dropped MP3', () => {
  const frame = (id, text) => { const t = new TextEncoder().encode(text); const f = new Uint8Array(10 + 1 + t.length); f.set(new TextEncoder().encode(id)); const n = t.length + 1; f[4] = (n >>> 24) & 255; f[5] = (n >>> 16) & 255; f[6] = (n >>> 8) & 255; f[7] = n & 255; f[10] = 3; f.set(t, 11); return f; };
  const frames = [frame('TPE1', 'Artist'), frame('TIT2', 'Song')];
  const len = frames.reduce((a, f) => a + f.length, 0);
  const buf = new Uint8Array(10 + len); buf.set([0x49, 0x44, 0x33, 3, 0, 0, 0, 0, (len >> 7) & 127, len & 127]);
  let o = 10; for (const f of frames) { buf.set(f, o); o += f.length; }
  assert.deepEqual(readId3(buf.buffer), { artist: 'Artist', title: 'Song' });
  assert.deepEqual(readId3(new ArrayBuffer(4)), {});
});
